// Regenerates the glyph outlines that circuit SVG export uses to draw labels
// without fonts. Run `node generate_circuit_svg_glyphs.js` after updating the
// KaTeX fonts embedded by ux/circuit-vis/renderer/circuitSvgFonts.ts.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import opentype from "three/addons/libs/opentype.module.js";

const thisDir = dirname(fileURLToPath(import.meta.url));
const fontDir = join(
  thisDir,
  "..",
  "..",
  "..",
  "node_modules",
  "katex",
  "dist",
  "fonts",
);
const rendererDir = join(thisDir, "ux", "circuit-vis", "renderer");
const embeddedFonts = readFileSync(
  join(rendererDir, "circuitSvgFonts.ts"),
  "utf8",
);

let hashes = "";
let tables = "";
for (const [file, name] of [
  ["KaTeX_Main-Regular", "KATEX_MAIN_REGULAR_GLYPHS"],
  ["KaTeX_Math-Italic", "KATEX_MATH_ITALIC_GLYPHS"],
]) {
  // Outlines must come from the same KaTeX release as the embedded fallback fonts.
  if (!embeddedFonts.includes(sha256(join(fontDir, `${file}.woff2`)))) {
    throw new Error(
      `${file}.woff2 does not match the font embedded in circuitSvgFonts.ts.`,
    );
  }
  const ttf = readFileSync(join(fontDir, `${file}.ttf`));
  const font = opentype.parse(
    ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength),
  );
  if (font.unitsPerEm !== 1000) {
    throw new Error(`${file}.ttf does not use 1000 units per em.`);
  }

  const glyphs = Object.entries(font.tables.cmap.glyphIndexMap)
    .map(([codePoint, index]) => [Number(codePoint), font.glyphs.get(index)])
    .sort(([a], [b]) => a - b)
    .map(
      ([codePoint, glyph]) =>
        `${codePoint}: [${glyph.advanceWidth}, ${JSON.stringify(pathData(glyph.getPath(0, 0, 1000)))}],`,
    );
  hashes += `// ${file}.ttf SHA-256:\n// ${sha256(join(fontDir, `${file}.ttf`))}\n`;
  tables += `
export const ${name}: CircuitSvgGlyphFont = {
  xHeight: ${font.tables.os2.sxHeight},
  ascent: ${font.ascender},
  descent: ${-font.descender},
  glyphs: {
${glyphs.join("\n")}
  },
};
`;
}

const source = `// Copyright (c) Microsoft Corporation.
// Licensed under the MIT License.

// Generated by generate_circuit_svg_glyphs.js from the KaTeX fonts embedded in
// circuitSvgFonts.ts. Do not edit by hand.
${hashes}
// Each font lists every code point in its character map as [advance, path],
// in font units (1000 per em) with y increasing downward from the baseline.
export type CircuitSvgGlyphFont = {
  xHeight: number;
  ascent: number;
  descent: number;
  glyphs: Readonly<Record<number, readonly [advance: number, path: string]>>;
};
${tables}`;

const target = join(rendererDir, "circuitSvgGlyphs.ts");
writeFileSync(target, await prettier.format(source, { parser: "typescript" }));
console.log(`Wrote ${target}`);

/** @param {string} path */
function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

/**
 * Formats a glyph path compactly, skipping the zero-length line segments that
 * opentype.js emits after curves.
 *
 * @param {{ commands: any[] }} path
 */
function pathData(path) {
  let data = "";
  let x = 0;
  let y = 0;
  for (const command of path.commands) {
    if (command.type === "Z") {
      data += "Z";
      continue;
    }
    if (command.type === "L" && command.x === x && command.y === y) {
      continue;
    }
    const values =
      command.type === "Q"
        ? [command.x1, command.y1, command.x, command.y]
        : command.type === "C"
          ? [
              command.x1,
              command.y1,
              command.x2,
              command.y2,
              command.x,
              command.y,
            ]
          : [command.x, command.y];
    data +=
      command.type +
      values
        .map((value) => Math.round(value * 10) / 10)
        .join(" ")
        .replaceAll(" -", "-");
    ({ x, y } = command);
  }
  return data;
}
