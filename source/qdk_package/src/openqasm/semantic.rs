/// Builds the semantic [`SemProgram`] root from an analyzed program.
pub(crate) fn build_program(
    py: Python<'_>,
    program: &sem::Program,
    ctx: &BuildContext<'_>,
    document: Py<SourceDocument>,
) -> PyResult<Py<SemProgram>> {
    let statements = stmt_list(py, &program.statements, ctx)?;
    let mut pragmas = Vec::with_capacity(program.pragmas.len());
    for pragma in &program.pragmas {
        pragmas.push(build_pragma(py, pragma)?);
    }
    let version = program.version.map(|version| version.to_string());
    let init = PyClassInitializer::from(QASMNode {
        span: Span::from(program.span),
    })
    .add_subclass(SemProgram {
        version,
        pragmas,
        statements,
        document,
    });
    Py::new(py, init)
}

fn build_pragma(py: Python<'_>, pragma: &sem::Pragma) -> PyResult<Py<PyAny>> {
    let command = pragma.command.to_string();
    let name = pragma.identifier.as_ref().map(PathKind::as_string);
    let value = pragma.value.as_ref().map(ToString::to_string);
    let init = SemPragma::init(Span::from(pragma.span), Vec::new(), command, name, value);
    Ok(Py::new(py, init)?.into_any())
}

#[allow(clippy::too_many_lines)]
fn build_stmt(py: Python<'_>, stmt: &sem::Stmt, ctx: &BuildContext<'_>) -> PyResult<Py<PyAny>> {
    let span = Span::from(stmt.span);
    let annotations = build_annotations(py, &stmt.annotations)?;

    let obj: Py<PyAny> = match stmt.kind.as_ref() {
        StmtKind::Alias(s) => {
            let exprs = expr_list(py, &s.exprs, ctx)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(py, SemAliasDecl::init(span, annotations, name, exprs))?.into_any()
        }
        StmtKind::Assign(s) => {
            let lhs = build_expr(py, &s.lhs, ctx)?;
            let rhs = build_expr(py, &s.rhs, ctx)?;
            Py::new(py, SemAssign::init(span, annotations, lhs, rhs))?.into_any()
        }
        StmtKind::Barrier(s) => {
            let qubits = gate_operand_list(py, &s.qubits, ctx)?;
            Py::new(py, SemBarrier::init(span, annotations, qubits))?.into_any()
        }
        StmtKind::Box(s) => {
            let duration = build_opt_expr(py, s.duration.as_deref(), ctx)?;
            let body = stmt_list(py, &s.body, ctx)?;
            Py::new(py, SemBox::init(span, annotations, duration, body))?.into_any()
        }
        StmtKind::Block(s) => {
            let statements = stmt_list(py, &s.stmts, ctx)?;
            Py::new(py, SemBlock::init(span, annotations, statements))?.into_any()
        }
        StmtKind::Break(_) => Py::new(py, SemBreak::init(span, annotations))?.into_any(),
        StmtKind::Calibration(s) => Py::new(
            py,
            SemCalibration::init(span, annotations, s.content.to_string()),
        )?
        .into_any(),
        StmtKind::CalibrationGrammar(s) => Py::new(
            py,
            SemCalibrationGrammar::init(span, annotations, s.name.to_string()),
        )?
        .into_any(),
        StmtKind::ClassicalDecl(s) => {
            let r#type = symbol_type(py, ctx, s.symbol_id)?;
            let init_expr = build_expr(py, &s.init_expr, ctx)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(
                py,
                SemClassicalDecl::init(span, annotations, name, r#type, init_expr),
            )?
            .into_any()
        }
        StmtKind::Continue(_) => Py::new(py, SemContinue::init(span, annotations))?.into_any(),
        StmtKind::Def(s) => {
            let mut params = Vec::with_capacity(s.params.len());
            for param in &s.params {
                let r#type = symbol_type(py, ctx, param.symbol_id)?;
                let symbol = build_symbol(py, ctx, param.symbol_id)?;
                params.push(
                    Py::new(
                        py,
                        SemSubroutineParameter::init(
                            Span::from(param.span),
                            symbol_name(ctx, param.symbol_id),
                            symbol,
                            r#type,
                        ),
                    )?
                    .into_any(),
                );
            }
            let return_type = subroutine_return_type(py, ctx, s.symbol_id)?;
            let body = stmt_list(py, &s.body.stmts, ctx)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(
                py,
                SemDef::init(span, annotations, name, params, return_type, body),
            )?
            .into_any()
        }
        StmtKind::DefCal(s) => Py::new(
            py,
            SemDefCal::init(span, annotations, s.content.to_string()),
        )?
        .into_any(),
        StmtKind::Delay(s) => {
            let duration = build_expr(py, &s.duration, ctx)?;
            let qubits = gate_operand_list(py, &s.qubits, ctx)?;
            Py::new(py, SemDelay::init(span, annotations, duration, qubits))?.into_any()
        }
        StmtKind::End(_) => Py::new(py, SemEnd::init(span, annotations))?.into_any(),
        StmtKind::ExprStmt(s) => {
            let expr = build_expr(py, &s.expr, ctx)?;
            Py::new(py, SemExprStmt::init(span, annotations, expr))?.into_any()
        }
        StmtKind::ExternDecl(s) => {
            let r#type = symbol_type(py, ctx, s.symbol_id)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(py, SemExternDecl::init(span, annotations, name, r#type))?.into_any()
        }
        StmtKind::For(s) => {
            let r#type = symbol_type(py, ctx, s.loop_variable)?;
            let iterable = build_enumerable_set(py, &s.set_declaration, ctx)?;
            let body = build_stmt(py, &s.body, ctx)?;
            let name = symbol_name(ctx, s.loop_variable);
            Py::new(
                py,
                SemForLoop::init(span, annotations, name, r#type, iterable, body),
            )?
            .into_any()
        }
        StmtKind::GateCall(s) => {
            let mut modifiers = Vec::with_capacity(s.modifiers.len());
            for modifier in s.modifiers.iter().rev() {
                modifiers.push(build_modifier(py, modifier, ctx)?);
            }
            let args = expr_list(py, &s.args, ctx)?;
            let qubits = gate_operand_list(py, &s.qubits, ctx)?;
            let duration = build_opt_expr(py, s.duration.as_deref(), ctx)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(
                py,
                SemGateCall::init(span, annotations, name, modifiers, args, qubits, duration),
            )?
            .into_any()
        }
        StmtKind::If(s) => {
            let condition = build_expr(py, &s.condition, ctx)?;
            let then_block = build_stmt(py, &s.if_body, ctx)?;
            let else_block = match &s.else_body {
                Some(else_body) => Some(build_stmt(py, else_body, ctx)?),
                None => None,
            };
            Py::new(
                py,
                SemIfStmt::init(span, annotations, condition, then_block, else_block),
            )?
            .into_any()
        }
        StmtKind::IndexedAssign(s) => {
            let lhs = build_expr(py, &s.lhs, ctx)?;
            let mut indices = Vec::with_capacity(s.indices.len());
            for index in &s.indices {
                indices.push(build_index(py, index, ctx)?);
            }
            let rhs = build_expr(py, &s.rhs, ctx)?;
            Py::new(
                py,
                SemIndexedAssign::init(span, annotations, lhs, indices, rhs),
            )?
            .into_any()
        }
        StmtKind::InputDeclaration(s) => {
            let r#type = symbol_type(py, ctx, s.symbol_id)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(
                py,
                SemInputDeclaration::init(span, annotations, name, r#type),
            )?
            .into_any()
        }
        StmtKind::OutputDeclaration(s) => {
            let r#type = symbol_type(py, ctx, s.symbol_id)?;
            let init_expr = build_expr(py, &s.init_expr, ctx)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(
                py,
                SemOutputDeclaration::init(span, annotations, name, r#type, init_expr),
            )?
            .into_any()
        }
        StmtKind::Pragma(s) => {
            let command = s.command.to_string();
            let name = s.identifier.as_ref().map(PathKind::as_string);
            let value = s.value.as_ref().map(ToString::to_string);
            Py::new(py, SemPragma::init(span, annotations, command, name, value))?.into_any()
        }
        StmtKind::QuantumGateDefinition(s) => {
            let params = gate_parameter_list(py, ctx, &s.params)?;
            let qubits = gate_parameter_list(py, ctx, &s.qubits)?;
            let body = stmt_list(py, &s.body.stmts, ctx)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(
                py,
                SemGateDefinition::init(span, annotations, name, params, qubits, body),
            )?
            .into_any()
        }
        StmtKind::QubitDecl(s) => {
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(py, SemQubitDecl::init(span, annotations, name))?.into_any()
        }
        StmtKind::QubitArrayDecl(s) => {
            let size = build_expr(py, &s.size, ctx)?;
            let name = symbol_name(ctx, s.symbol_id);
            Py::new(py, SemQubitArrayDecl::init(span, annotations, name, size))?.into_any()
        }
        StmtKind::Reset(s) => {
            let mut qubits = Vec::new();
            collect_gate_operand(py, &mut qubits, &s.operand, ctx)?;
            Py::new(py, SemReset::init(span, annotations, qubits))?.into_any()
        }
        StmtKind::Return(s) => {
            let value = build_opt_expr(py, s.expr.as_deref(), ctx)?;
            Py::new(py, SemReturn::init(span, annotations, value))?.into_any()
        }
        StmtKind::Switch(s) => {
            let target = build_expr(py, &s.target, ctx)?;
            let mut cases = Vec::with_capacity(s.cases.len());
            for case in &s.cases {
                let labels = expr_list(py, &case.labels, ctx)?;
                let body = stmt_list(py, &case.block.stmts, ctx)?;
                cases.push(
                    Py::new(py, SemSwitchCase::init(Span::from(case.span), labels, body))?
                        .into_any(),
                );
            }
            let default = s
                .default
                .as_ref()
                .map(|block| stmt_list(py, &block.stmts, ctx))
                .transpose()?;
            Py::new(
                py,
                SemSwitch::init(span, annotations, target, cases, default),
            )?
            .into_any()
        }
        StmtKind::WhileLoop(s) => {
            let condition = build_expr(py, &s.condition, ctx)?;
            let body = build_stmt(py, &s.body, ctx)?;
            Py::new(py, SemWhileLoop::init(span, annotations, condition, body))?.into_any()
        }
        // Includes are inlined by `lower_source` and rejected outside global scope, so the
        // variant never reaches the projection. Surface it as a recovery node, not a panic.
        StmtKind::Err => Py::new(py, SemErrStmt::init(span, annotations))?.into_any(),
    };
    Ok(obj)
}

fn build_annotations(
    py: Python<'_>,
    annotations: &[sem::Annotation],
) -> PyResult<Vec<Py<Annotation>>> {
    annotations
        .iter()
        .map(|annotation| {
            Py::new(
                py,
                Annotation::init(
                    Span::from(annotation.span),
                    annotation.identifier.as_string(),
                    annotation.value.as_ref().map(ToString::to_string),
                    annotation.value_span.map(Span::from),
                ),
            )
        })
        .collect()
}

#[allow(clippy::too_many_lines)]
fn build_expr(py: Python<'_>, expr: &sem::Expr, ctx: &BuildContext<'_>) -> PyResult<Py<PyAny>> {
    let span = Span::from(expr.span);
    let ty = build_type(py, ctx, &expr.ty)?;
    let const_value = literal_value(py, expr.const_value.as_ref())?;

    let obj: Py<PyAny> = match expr.kind.as_ref() {
        ExprKind::Err => Py::new(py, SemErrExpr::init(span, ty, const_value, None))?.into_any(),
        ExprKind::ResolvedIdent(id) => {
            let symbol = Some(build_symbol(py, ctx, *id)?);
            let name = symbol_name(ctx, *id);
            Py::new(
                py,
                SemResolvedIdent::init(span, ty, const_value, symbol, name),
            )?
            .into_any()
        }
        ExprKind::CapturedResolvedIdent(id) => {
            let symbol = Some(build_symbol(py, ctx, *id)?);
            let name = symbol_name(ctx, *id);
            Py::new(
                py,
                SemCapturedResolvedIdent::init(span, ty, const_value, symbol, name),
            )?
            .into_any()
        }
        ExprKind::UnaryOp(e) => {
            let operand = build_expr(py, &e.expr, ctx)?;
            Py::new(
                py,
                SemUnaryOpExpr::init(span, ty, const_value, None, e.op.into(), operand),
            )?
            .into_any()
        }
        ExprKind::BinaryOp(e) => {
            let lhs = build_expr(py, &e.lhs, ctx)?;
            let rhs = build_expr(py, &e.rhs, ctx)?;
            Py::new(
                py,
                SemBinaryOpExpr::init(span, ty, const_value, None, e.op.into(), lhs, rhs),
            )?
            .into_any()
        }
        ExprKind::Lit(lit) => {
            let (value, elements) = literal_expr_parts(py, lit, ctx)?;
            Py::new(
                py,
                SemLiteral::init(span, ty, const_value, None, value, elements),
            )?
            .into_any()
        }
        ExprKind::ResolvedFunctionCall(e) => {
            let args = expr_list(py, &e.args, ctx)?;
            let symbol = Some(build_symbol(py, ctx, e.callee_id)?);
            let name = symbol_name(ctx, e.callee_id);
            Py::new(
                py,
                SemFunctionCall::init(span, ty, const_value, symbol, name, args),
            )?
            .into_any()
        }
        ExprKind::BuiltinFunctionCall(e) => {
            let args = expr_list(py, &e.args, ctx)?;
            Py::new(
                py,
                SemBuiltinFunctionCall::init(span, ty, const_value, None, e.name.to_string(), args),
            )?
            .into_any()
        }
        ExprKind::Cast(e) => {
            let operand = build_expr(py, &e.expr, ctx)?;
            Py::new(
                py,
                SemCast::init(span, ty, const_value, None, operand, e.kind.into()),
            )?
            .into_any()
        }
        ExprKind::IndexedExpr(e) => {
            let collection = build_expr(py, &e.collection, ctx)?;
            let indices = vec![build_index(py, &e.index, ctx)?];
            Py::new(
                py,
                SemIndexedExpr::init(span, ty, const_value, None, collection, indices),
            )?
            .into_any()
        }
        ExprKind::Paren(inner) => {
            let operand = build_expr(py, inner, ctx)?;
            Py::new(py, SemParen::init(span, ty, const_value, None, operand))?.into_any()
        }
        ExprKind::Measure(e) => {
            let mut qubits = Vec::new();
            collect_gate_operand(py, &mut qubits, &e.operand, ctx)?;
            Py::new(py, SemMeasure::init(span, ty, const_value, None, qubits))?.into_any()
        }
        ExprKind::RuntimeSizeof(e) => {
            let array = build_expr(py, &e.array, ctx)?;
            let dimension = build_expr(py, &e.dimension, ctx)?;
            Py::new(
                py,
                SemRuntimeSizeof::init(span, ty, const_value, None, array, dimension, e.array_rank),
            )?
            .into_any()
        }
        ExprKind::EvaluatedDurationof(e) => {
            let body = stmt_list(py, &e.scope.stmts, ctx)?;
            Py::new(
                py,
                SemEvaluatedDurationof::init(span, ty, const_value, None, body),
            )?
            .into_any()
        }
        ExprKind::Concat(e) => {
            let operands = expr_list(py, &e.operands, ctx)?;
            Py::new(py, SemConcat::init(span, ty, const_value, None, operands))?.into_any()
        }
    };
    Ok(obj)
}

