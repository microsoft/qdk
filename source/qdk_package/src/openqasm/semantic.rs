fn expr_list(
    py: Python<'_>,
    exprs: &[sem::Expr],
    ctx: &BuildContext<'_>,
) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(exprs.len());
    for expr in exprs {
        out.push(build_expr(py, expr, ctx)?);
    }
    Ok(out)
}

fn stmt_list(
    py: Python<'_>,
    stmts: &[sem::Stmt],
    ctx: &BuildContext<'_>,
) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(stmts.len());
    for stmt in stmts {
        if let StmtKind::GateCall(call) = stmt.kind.as_ref() {
            let expansion =
                expand_gate_call(call).map_err(|error| PyValueError::new_err(error.to_string()))?;
            for scalar in expansion {
                out.push(build_scalar_gate_call(py, stmt, &scalar, ctx)?);
            }
        } else {
            out.push(build_stmt(py, stmt, ctx)?);
        }
    }
    Ok(out)
}

fn build_scalar_gate_call(
    py: Python<'_>,
    stmt: &sem::Stmt,
    scalar: &ScalarGateCall<'_>,
    ctx: &BuildContext<'_>,
) -> PyResult<Py<PyAny>> {
    let call = scalar.source();
    let span = Span::from(stmt.span);
    let annotations = build_annotations(py, &stmt.annotations)?;
    let mut modifiers = Vec::with_capacity(call.modifiers.len());
    for modifier in call.modifiers.iter().rev() {
        modifiers.push(build_modifier(py, modifier, ctx)?);
    }
    let args = expr_list(py, &call.args, ctx)?;
    let qubits = gate_operand_list(py, scalar.qubits(), ctx)?;
    let duration = build_opt_expr(py, call.duration.as_deref(), ctx)?;
    let name = symbol_name(ctx, call.symbol_id);
    Ok(Py::new(
        py,
        SemGateCall::init(span, annotations, name, modifiers, args, qubits, duration),
    )?
    .into_any())
}

fn build_opt_expr(
    py: Python<'_>,
    expr: Option<&sem::Expr>,
    ctx: &BuildContext<'_>,
) -> PyResult<Option<Py<PyAny>>> {
    match expr {
        Some(expr) => Ok(Some(build_expr(py, expr, ctx)?)),
        None => Ok(None),
    }
}

fn gate_operand_list(
    py: Python<'_>,
    operands: &[sem::GateOperand],
    ctx: &BuildContext<'_>,
) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(operands.len());
    for operand in operands {
        collect_gate_operand(py, &mut out, operand, ctx)?;
    }
    Ok(out)
}

fn collect_gate_operand(
    py: Python<'_>,
    out: &mut Vec<Py<PyAny>>,
    operand: &sem::GateOperand,
    ctx: &BuildContext<'_>,
) -> PyResult<()> {
    match &operand.kind {
        sem::GateOperandKind::Expr(expr) => out.push(build_expr(py, expr, ctx)?),
        sem::GateOperandKind::HardwareQubit(hw) => out.push(build_hardware_qubit(py, ctx, hw)?),
        sem::GateOperandKind::Err => {}
    }
    Ok(())
}

fn build_hardware_qubit(
    py: Python<'_>,
    ctx: &BuildContext<'_>,
    hw: &sem::HardwareQubit,
) -> PyResult<Py<PyAny>> {
    let init = sem_expr_base(
        Span::from(hw.span),
        build_type(py, ctx, &hw.ty)?,
        None,
        None,
    )
    .add_subclass(SemHardwareQubit {
        name: hw.name.to_string(),
    });
    Ok(Py::new(py, init)?.into_any())
}

fn build_index(py: Python<'_>, index: &sem::Index, ctx: &BuildContext<'_>) -> PyResult<Py<PyAny>> {
    match index {
        sem::Index::Expr(expr) => build_expr(py, expr, ctx),
        sem::Index::Range(range) => build_range(py, range, ctx),
    }
}

fn build_range(py: Python<'_>, range: &sem::Range, ctx: &BuildContext<'_>) -> PyResult<Py<PyAny>> {
    let start = build_opt_expr(py, range.start.as_ref(), ctx)?;
    let step = build_opt_expr(py, range.step.as_ref(), ctx)?;
    let end = build_opt_expr(py, range.end.as_ref(), ctx)?;
    Ok(Py::new(
        py,
        SemRangeDefinition::init(
            Span::from(range.span),
            build_type(py, ctx, &range.ty)?,
            start,
            step,
            end,
        ),
    )?
    .into_any())
}

fn build_enumerable_set(
    py: Python<'_>,
    set: &sem::EnumerableSet,
    ctx: &BuildContext<'_>,
) -> PyResult<Py<PyAny>> {
    match set {
        sem::EnumerableSet::Set(set) => {
            let values = expr_list(py, &set.values, ctx)?;
            Ok(Py::new(
                py,
                SemDiscreteSet::init(Span::from(set.span), build_type(py, ctx, &set.ty)?, values),
            )?
            .into_any())
        }
        sem::EnumerableSet::Range(range) => build_range(py, range, ctx),
        sem::EnumerableSet::Expr(expr) => build_expr(py, expr, ctx),
    }
}

fn build_modifier(
    py: Python<'_>,
    modifier: &sem::QuantumGateModifier,
    ctx: &BuildContext<'_>,
) -> PyResult<Py<PyAny>> {
    let (name, argument) = match &modifier.kind {
        sem::GateModifierKind::Inv => (GateModifierName::Inv, None),
        sem::GateModifierKind::Pow(expr) => {
            (GateModifierName::Pow, Some(build_expr(py, expr, ctx)?))
        }
        sem::GateModifierKind::Ctrl(expr) => {
            (GateModifierName::Ctrl, Some(build_expr(py, expr, ctx)?))
        }
        sem::GateModifierKind::NegCtrl(expr) => {
            (GateModifierName::NegCtrl, Some(build_expr(py, expr, ctx)?))
        }
    };
    Ok(Py::new(
        py,
        SemQuantumGateModifier::init(Span::from(modifier.span), name, argument),
    )?
    .into_any())
}

