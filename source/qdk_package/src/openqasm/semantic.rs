/// Projects a resolved type onto its concrete Python node.
///
/// Nodes are interned per analysis. They are frozen and compare structurally, so
/// sharing one object across every occurrence of a type is unobservable.
fn build_type(py: Python<'_>, ctx: &BuildContext<'_>, ty: &CoreType) -> PyResult<Py<PyAny>> {
    if let Some(node) = ctx.cached_type(py, ty) {
        return Ok(node);
    }
    let node = project_type(py, ctx, ty)?;
    ctx.cache_type(py, ty, &node);
    Ok(node)
}

fn project_type(py: Python<'_>, ctx: &BuildContext<'_>, ty: &CoreType) -> PyResult<Py<PyAny>> {
    let name = ty.to_string();
    let is_const = ty.is_const();
    let node = match ty {
        CoreType::Int(size, _) => Py::new(py, SemIntType::init(name, is_const, *size))?.into_any(),
        CoreType::UInt(size, _) => {
            Py::new(py, SemUintType::init(name, is_const, *size))?.into_any()
        }
        CoreType::Float(size, _) => {
            Py::new(py, SemFloatType::init(name, is_const, *size))?.into_any()
        }
        CoreType::Angle(size, _) => {
            Py::new(py, SemAngleType::init(name, is_const, *size))?.into_any()
        }
        CoreType::Complex(size, _) => {
            Py::new(py, SemComplexType::init(name, is_const, *size))?.into_any()
        }
        CoreType::Bit(_) => Py::new(py, SemBitType::init(name, is_const))?.into_any(),
        CoreType::Bool(_) => Py::new(py, SemBoolType::init(name, is_const))?.into_any(),
        CoreType::Duration(_) => Py::new(py, SemDurationType::init(name, is_const))?.into_any(),
        CoreType::Stretch(_) => Py::new(py, SemStretchType::init(name, is_const))?.into_any(),
        CoreType::Qubit => Py::new(py, SemQubitType::init(name, is_const))?.into_any(),
        CoreType::HardwareQubit => {
            Py::new(py, SemHardwareQubitType::init(name, is_const))?.into_any()
        }
        CoreType::BitArray(size, _) => {
            Py::new(py, SemBitArrayType::init(name, is_const, *size))?.into_any()
        }
        CoreType::QubitArray(size) => {
            Py::new(py, SemQubitArrayType::init(name, is_const, *size))?.into_any()
        }
        CoreType::Array(array) => {
            let base_type = build_type(py, ctx, &array.base_ty.clone().into())?;
            let dimensions = array_dimensions(&array.dims);
            Py::new(
                py,
                SemArrayType::init(name, is_const, base_type, dimensions),
            )?
            .into_any()
        }
        CoreType::StaticArrayRef(array) => {
            let base_type = build_type(py, ctx, &array.base_ty.clone().into())?;
            let dimensions = array_dimensions(&array.dims);
            Py::new(
                py,
                SemStaticArrayReferenceType::init(
                    name,
                    is_const,
                    base_type,
                    dimensions,
                    access_control(array.is_mutable),
                ),
            )?
            .into_any()
        }
        CoreType::RankedArrayRef(array) => {
            let base_type = build_type(py, ctx, &array.base_ty.clone().into())?;
            Py::new(
                py,
                SemDynArrayReferenceType::init(
                    name,
                    is_const,
                    base_type,
                    array.rank as u32,
                    access_control(array.is_mutable),
                ),
            )?
            .into_any()
        }
        CoreType::Gate(classical, qubits) => {
            Py::new(py, SemGateType::init(name, is_const, *classical, *qubits))?.into_any()
        }
        CoreType::Function(params, ret) => {
            let mut parameter_types = Vec::with_capacity(params.len());
            for param in params.iter() {
                parameter_types.push(build_type(py, ctx, param)?);
            }
            let return_type = build_type(py, ctx, ret)?;
            Py::new(
                py,
                SemFunctionType::init(name, is_const, parameter_types, return_type),
            )?
            .into_any()
        }
        CoreType::Range => Py::new(py, SemRangeType::init(name, is_const))?.into_any(),
        CoreType::Set => Py::new(py, SemSetType::init(name, is_const))?.into_any(),
        CoreType::Void => Py::new(py, SemVoidType::init(name, is_const))?.into_any(),
        CoreType::Err => Py::new(py, SemErrorType::init(name, is_const))?.into_any(),
    };
    Ok(node)
}

fn array_dimensions(dims: &ArrayDimensions) -> Vec<u32> {
    dims.clone().into_iter().collect()
}

fn access_control(is_mutable: bool) -> AccessControl {
    if is_mutable {
        AccessControl::Mutable
    } else {
        AccessControl::ReadOnly
    }
}

/// A read-only view of a resolved symbol.
#[pyclass(name = "Symbol", module = "qdk.openqasm.semantic", frozen)]
pub(crate) struct SemSymbol {
    /// The symbol's unique id within the [`SemSymbolTable`].
    #[pyo3(get)]
    id: u32,
    /// The symbol's name.
    #[pyo3(get)]
    name: String,
    /// The span where the symbol is declared.
    #[pyo3(get)]
    span: Span,
    /// The symbol's resolved type.
    #[pyo3(get)]
    ty: Py<PyAny>,
    /// Whether the symbol is a program input, a program output, or neither.
    #[pyo3(get)]
    io_kind: IOKind,
    /// The symbol's const-evaluated value, if it is a constant.
    #[pyo3(get)]
    const_value: Option<Py<PyAny>>,
}

#[pymethods]
impl SemSymbol {
    fn __repr__(&self) -> String {
        format!("Symbol(id={}, name={})", self.id, py_str(&self.name))
    }

    // A symbol participates in expression equality, so it needs structural
    // equality of its own or two parses of one source would compare unequal.
    //
    // `id` is excluded for the same reason the node-level `symbol_id` accessor
    // was removed: it is a position in the analysis table, so including it
    // would make two structurally identical subtrees compare unequal whenever
    // the declarations preceding them differ. `span` is excluded for the
    // matching reason: it is a source position, not structure.
    fn __eq__(slf: &Bound<'_, Self>, other: &Bound<'_, PyAny>) -> PyResult<bool> {
        crate::openqasm::eq::structural_eq(
            slf.as_any(),
            other,
            &["name", "ty", "io_kind", "const_value"],
        )
    }

    fn __hash__(slf: &Bound<'_, Self>) -> PyResult<isize> {
        crate::openqasm::eq::structural_hash(
            slf.as_any(),
            &["name", "ty", "io_kind", "const_value"],
        )
    }
}

/// An iterable, read-only projection of the resolved symbol table.
#[pyclass(name = "SymbolTable", module = "qdk.openqasm.semantic", frozen)]
pub(crate) struct SemSymbolTable {
    symbols: Vec<Py<SemSymbol>>,
}

#[pymethods]
impl SemSymbolTable {
    /// The number of symbols in the table.
    fn __len__(&self) -> usize {
        self.symbols.len()
    }
    /// Iterates over the [`SemSymbol`] views in the table.
    fn __iter__(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        let list = PyList::new(py, self.symbols.iter().map(|symbol| symbol.clone_ref(py)))?;
        Ok(list.as_any().try_iter()?.into_any().unbind())
    }

    /// Returns the symbol with the given id, or `None`.
    fn get(&self, py: Python<'_>, id: u32) -> Option<Py<SemSymbol>> {
        self.symbols
            .iter()
            .find(|symbol| symbol.borrow(py).id == id)
            .map(|symbol| symbol.clone_ref(py))
    }

    /// Returns the first symbol with the given name, or `None`.
    fn lookup(&self, py: Python<'_>, name: &str) -> Option<Py<SemSymbol>> {
        self.symbols
            .iter()
            .find(|symbol| symbol.borrow(py).name == name)
            .map(|symbol| symbol.clone_ref(py))
    }

    /// All [`SemSymbol`] views in the table, in id order.
    fn symbols(&self, py: Python<'_>) -> Vec<Py<SemSymbol>> {
        self.symbols
            .iter()
            .map(|symbol| symbol.clone_ref(py))
            .collect()
    }

    fn __repr__(&self) -> String {
        format!("SymbolTable({})", py_items(self.symbols.len()))
    }
}

fn build_sem_symbol(
    py: Python<'_>,
    ctx: &BuildContext<'_>,
    id: u32,
    symbol: &Symbol,
) -> PyResult<Py<SemSymbol>> {
    if let Some(node) = ctx.cached_symbol(py, id) {
        return Ok(node);
    }
    let node = Py::new(
        py,
        SemSymbol {
            id,
            name: symbol.name.clone(),
            span: symbol.span.into(),
            ty: build_type(py, ctx, &symbol.ty)?,
            io_kind: IOKind::from(symbol.io_kind),
            const_value: literal_value(py, symbol.get_const_value().as_ref())?,
        },
    )?;
    ctx.cache_symbol(py, id, &node);
    Ok(node)
}

/// Builds the iterable [`SemSymbolTable`] projection from the resolved table.
///
/// Symbol ids are assigned sequentially as symbols are inserted, and the
/// underlying storage never leaves gaps, so a symbol's insertion index equals
/// its id.
pub(crate) fn build_symbol_table(
    py: Python<'_>,
    ctx: &BuildContext<'_>,
) -> PyResult<Py<SemSymbolTable>> {
    let mut entries = Vec::new();
    for (index, symbol) in ctx.symbols.symbols().enumerate() {
        let id = u32::try_from(index).expect("symbol id should fit into u32");
        entries.push(build_sem_symbol(py, ctx, id, symbol.as_ref())?);
    }
    Py::new(py, SemSymbolTable { symbols: entries })
}

fn build_symbol(py: Python<'_>, ctx: &BuildContext<'_>, id: SymbolId) -> PyResult<Py<SemSymbol>> {
    build_sem_symbol(py, ctx, id.into(), ctx.symbols[id].as_ref())
}

fn symbol_name(ctx: &BuildContext<'_>, id: SymbolId) -> Option<String> {
    Some(ctx.symbols[id].name.clone())
}

/// Projects a gate definition's formal parameters as span-carrying nodes.
///
/// The crate stores them as `SymbolId`s, so each node's span is the symbol's
/// own declaration span, which is where the parameter is written.
fn gate_parameter_list(
    py: Python<'_>,
    ctx: &BuildContext<'_>,
    ids: &[SymbolId],
) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(ids.len());
    for id in ids {
        let symbol = ctx.symbols[*id].as_ref();
        out.push(
            Py::new(
                py,
                SemGateParameter::init(
                    symbol.span.into(),
                    symbol_name(ctx, *id),
                    build_symbol(py, ctx, *id)?,
                    symbol_type(py, ctx, *id)?,
                ),
            )?
            .into_any(),
        );
    }
    Ok(out)
}

/// Projects the resolved type a declaration bound to its symbol.
fn symbol_type(py: Python<'_>, ctx: &BuildContext<'_>, id: SymbolId) -> PyResult<Py<PyAny>> {
    build_type(py, ctx, &ctx.symbols[id].ty)
}

/// Projects a subroutine's return type out of the `Function` type on its symbol.
fn subroutine_return_type(
    py: Python<'_>,
    ctx: &BuildContext<'_>,
    id: SymbolId,
) -> PyResult<Py<PyAny>> {
    match &ctx.symbols[id].ty {
        CoreType::Function(_, return_ty) => build_type(py, ctx, return_ty),
        other => build_type(py, ctx, other),
    }
}

