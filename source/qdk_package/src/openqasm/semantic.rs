/// State shared by every builder for the duration of one analysis projection.
///
/// The caches are the reason this exists. `build_type` and `build_sem_symbol`
/// are pure functions of the resolved data they project, and a program refers to
/// the same handful of types and symbols thousands of times, so without
/// interning a 320,000-node tree carried roughly 260,000 type objects for a
/// handful of distinct values and one symbol object per identifier occurrence.
pub(crate) struct BuildContext<'a> {
    symbols: &'a SymbolTable,
    types: RefCell<FxHashMap<CoreType, Py<PyAny>>>,
    symbol_nodes: RefCell<FxHashMap<u32, Py<SemSymbol>>>,
}

impl<'a> BuildContext<'a> {
    pub(crate) fn new(symbols: &'a SymbolTable) -> Self {
        Self {
            symbols,
            types: RefCell::new(FxHashMap::default()),
            symbol_nodes: RefCell::new(FxHashMap::default()),
        }
    }

    /// Returns the shared node for an already-projected type, if there is one.
    fn cached_type(&self, py: Python<'_>, ty: &CoreType) -> Option<Py<PyAny>> {
        self.types.borrow().get(ty).map(|node| node.clone_ref(py))
    }

    fn cache_type(&self, py: Python<'_>, ty: &CoreType, node: &Py<PyAny>) {
        self.types
            .borrow_mut()
            .insert(ty.clone(), node.clone_ref(py));
    }

    fn cached_symbol(&self, py: Python<'_>, id: u32) -> Option<Py<SemSymbol>> {
        self.symbol_nodes
            .borrow()
            .get(&id)
            .map(|node| node.clone_ref(py))
    }

    fn cache_symbol(&self, py: Python<'_>, id: u32, node: &Py<SemSymbol>) {
        self.symbol_nodes
            .borrow_mut()
            .insert(id, node.clone_ref(py));
    }
}

