/// Builds the literal node for a `Lit` expression.
///
/// Each `ast::LiteralKind` variant maps to its own class so callers dispatch on
/// the node type instead of a string tag.
fn build_literal(py: Python<'_>, span: Span, lit: &ast::LiteralKind) -> PyResult<Py<PyAny>> {
    use ast::LiteralKind as Kind;
    let obj: Py<PyAny> = match lit {
        Kind::Array(exprs) => {
            let values = expr_list(py, exprs)?;
            Py::new(py, ArrayLiteral::init(span, values))?.into_any()
        }
        Kind::Bool(value) => Py::new(py, BooleanLiteral::init(span, *value))?.into_any(),
        Kind::Int(value) => {
            Py::new(py, IntegerLiteral::init(span, (*value).into_py_any(py)?))?.into_any()
        }
        Kind::BigInt(value) => {
            let value = bigint_to_py(py, &value.to_str_radix(10))?;
            Py::new(py, IntegerLiteral::init(span, value))?.into_any()
        }
        Kind::Float(value) => Py::new(py, FloatLiteral::init(span, *value))?.into_any(),
        Kind::Imaginary(value) => Py::new(py, ImaginaryLiteral::init(span, *value))?.into_any(),
        Kind::String(value) => {
            Py::new(py, StringLiteral::init(span, value.to_string()))?.into_any()
        }
        Kind::Duration(value, unit) => {
            Py::new(py, DurationLiteral::init(span, *value, unit.into()))?.into_any()
        }
        Kind::Bitstring(value, width) => {
            let value = bigint_to_py(py, &value.to_str_radix(10))?;
            Py::new(py, BitstringLiteral::init(span, value, *width))?.into_any()
        }
    };
    Ok(obj)
}

fn bigint_to_py(py: Python<'_>, decimal: &str) -> PyResult<Py<PyAny>> {
    Ok(py
        .import("builtins")?
        .getattr("int")?
        .call1((decimal,))?
        .unbind())
}
