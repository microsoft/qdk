/// Builds the initializer chain `QASMNode -> Expression`.
fn syntax_expr_base(span: Span) -> PyClassInitializer<Expression> {
    PyClassInitializer::from(QASMNode { span }).add_subclass(Expression)
}

/// Builds the initializer chain `QASMNode -> Statement`.
fn syntax_stmt_base(span: Span, annotations: Vec<Py<Annotation>>) -> PyClassInitializer<Statement> {
    PyClassInitializer::from(QASMNode { span }).add_subclass(Statement { annotations })
}

/// Builds the initializer chain `QASMNode -> ClassicalType`.
fn syntax_type_base(span: Span) -> PyClassInitializer<ClassicalType> {
    PyClassInitializer::from(QASMNode { span }).add_subclass(ClassicalType)
}

/// A binary operator.
///
/// Member names are descriptive because the `openqasm3` reference enum names
/// its members by symbol, which are not Python identifiers. The OpenQASM
