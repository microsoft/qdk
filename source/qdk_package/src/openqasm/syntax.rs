fn expr_list(py: Python<'_>, exprs: &[ast::Expr]) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(exprs.len());
    for expr in exprs {
        out.push(build_expr(py, expr)?);
    }
    Ok(out)
}

/// Projects a gate-definition parameter list, keeping recovery gaps visible.
///
/// A missing item becomes an `ErrorExpression` at the span it would have
/// occupied, so a caller can see the hole instead of a silently shorter list.
fn gate_ident_list(py: Python<'_>, items: &[ast::SeqItem<ast::Ident>]) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(items.len());
    for item in items {
        let node = if let Some(ident) = item.item_as_ref() {
            build_identifier(py, ident)?
        } else {
            let span = item.missing_span().unwrap_or_default();
            Py::new(py, ErrorExpression::init(Span::from(span)))?.into_any()
        };
        out.push(node);
    }
    Ok(out)
}

fn stmt_list(py: Python<'_>, stmts: &[ast::Stmt]) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(stmts.len());
    for stmt in stmts {
        out.push(build_stmt(py, stmt)?);
    }
    Ok(out)
}

fn opt_expr(py: Python<'_>, expr: Option<&ast::Expr>) -> PyResult<Option<Py<PyAny>>> {
    match expr {
        Some(expr) => Ok(Some(build_expr(py, expr)?)),
        None => Ok(None),
    }
}

fn build_type_definition(py: Python<'_>, ty: &ast::TypeDef) -> PyResult<Py<PyAny>> {
    match ty {
        ast::TypeDef::Scalar(ty) => build_scalar_type(py, ty),
        ast::TypeDef::Array(ty) => {
            let base_type = build_array_base_type(py, &ty.base_type, ty.span)?;
            let dimensions = expr_list(py, &ty.dimensions)?;
            let init = ArrayType::init(Span::from(ty.span), base_type, dimensions);
            Ok(Py::new(py, init)?.into_any())
        }
        ast::TypeDef::ArrayReference(ty) => build_array_reference_type(py, ty),
    }
}

fn build_extern_parameter_type(py: Python<'_>, ty: &ast::ExternParameter) -> PyResult<Py<PyAny>> {
    match ty {
        ast::ExternParameter::Scalar(ty, _) => build_scalar_type(py, ty),
        ast::ExternParameter::ArrayReference(ty, _) => build_array_reference_type(py, ty),
    }
}

fn build_def_parameter_type(py: Python<'_>, ty: &ast::DefParameterType) -> PyResult<Py<PyAny>> {
    match ty {
        ast::DefParameterType::Qubit(ty) => {
            let size = opt_expr(py, ty.size.as_ref())?;
            let init = QubitType::init(Span::from(ty.span), size);
            Ok(Py::new(py, init)?.into_any())
        }
        ast::DefParameterType::Scalar(ty) => build_scalar_type(py, ty),
        ast::DefParameterType::ArrayReference(ty) => build_array_reference_type(py, ty),
    }
}

fn build_scalar_type(py: Python<'_>, ty: &ast::ScalarType) -> PyResult<Py<PyAny>> {
    let span = Span::from(ty.span);
    let obj: Py<PyAny> = match &ty.kind {
        ast::ScalarTypeKind::Bit(ty) => {
            Py::new(py, BitType::init(span, opt_expr(py, ty.size.as_ref())?))?.into_any()
        }
        ast::ScalarTypeKind::Int(ty) => {
            Py::new(py, IntType::init(span, opt_expr(py, ty.size.as_ref())?))?.into_any()
        }
        ast::ScalarTypeKind::Uint(ty) => {
            Py::new(py, UintType::init(span, opt_expr(py, ty.size.as_ref())?))?.into_any()
        }
        ast::ScalarTypeKind::Float(ty) => {
            Py::new(py, FloatType::init(span, opt_expr(py, ty.size.as_ref())?))?.into_any()
        }
        ast::ScalarTypeKind::Angle(ty) => {
            Py::new(py, AngleType::init(span, opt_expr(py, ty.size.as_ref())?))?.into_any()
        }
        ast::ScalarTypeKind::Complex(ty) => {
            let base_type = match &ty.base_size {
                Some(base) => Some(build_float_type(py, base)?),
                None => None,
            };
            Py::new(py, ComplexType::init(span, base_type))?.into_any()
        }
        ast::ScalarTypeKind::BoolType => Py::new(py, BoolType::init(span))?.into_any(),
        ast::ScalarTypeKind::Duration => Py::new(py, DurationType::init(span))?.into_any(),
        ast::ScalarTypeKind::Stretch => Py::new(py, StretchType::init(span))?.into_any(),
        ast::ScalarTypeKind::Err => Py::new(py, ErrorType::init(span))?.into_any(),
    };
    Ok(obj)
}

fn build_float_type(py: Python<'_>, ty: &ast::FloatType) -> PyResult<Py<PyAny>> {
    let size = opt_expr(py, ty.size.as_ref())?;
    let init = FloatType::init(Span::from(ty.span), size);
    Ok(Py::new(py, init)?.into_any())
}

fn build_array_base_type(
    py: Python<'_>,
    kind: &ast::ArrayBaseTypeKind,
    span: qdk_openqasm::span::Span,
) -> PyResult<Py<PyAny>> {
    let py_span = Span::from(span);
    let obj: Py<PyAny> = match kind {
        ast::ArrayBaseTypeKind::Int(ty) => {
            Py::new(py, IntType::init(py_span, opt_expr(py, ty.size.as_ref())?))?.into_any()
        }
        ast::ArrayBaseTypeKind::Uint(ty) => {
            Py::new(py, UintType::init(py_span, opt_expr(py, ty.size.as_ref())?))?.into_any()
        }
        ast::ArrayBaseTypeKind::Float(ty) => Py::new(
            py,
            FloatType::init(py_span, opt_expr(py, ty.size.as_ref())?),
        )?
        .into_any(),
        ast::ArrayBaseTypeKind::Angle(ty) => Py::new(
            py,
            AngleType::init(py_span, opt_expr(py, ty.size.as_ref())?),
        )?
        .into_any(),
        ast::ArrayBaseTypeKind::Complex(ty) => {
            let base_type = match &ty.base_size {
                Some(base) => Some(build_float_type(py, base)?),
                None => None,
            };
            Py::new(py, ComplexType::init(py_span, base_type))?.into_any()
        }
        ast::ArrayBaseTypeKind::BoolType => Py::new(py, BoolType::init(py_span))?.into_any(),
        ast::ArrayBaseTypeKind::Duration => Py::new(py, DurationType::init(py_span))?.into_any(),
    };
    Ok(obj)
}

fn build_array_reference_type(py: Python<'_>, ty: &ast::ArrayReferenceType) -> PyResult<Py<PyAny>> {
    let obj: Py<PyAny> = match ty {
        ast::ArrayReferenceType::Static(ty) => {
            let base_type = build_array_base_type(py, &ty.base_type, ty.span)?;
            let dimensions = expr_list(py, &ty.dimensions)?;
            let init = StaticArrayReferenceType::init(
                Span::from(ty.span),
                base_type,
                dimensions,
                (&ty.mutability).into(),
            );
            Py::new(py, init)?.into_any()
        }
        ast::ArrayReferenceType::Dyn(ty) => {
            let base_type = build_array_base_type(py, &ty.base_type, ty.span)?;
            let num_dimensions = build_expr(py, &ty.dimensions)?;
            let init = DynArrayReferenceType::init(
                Span::from(ty.span),
                base_type,
                num_dimensions,
                (&ty.mutability).into(),
            );
            Py::new(py, init)?.into_any()
        }
    };
    Ok(obj)
}

fn modifier_list(
    py: Python<'_>,
    modifiers: &[ast::QuantumGateModifier],
) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(modifiers.len());
    for modifier in modifiers {
        out.push(build_modifier(py, modifier)?);
    }
    Ok(out)
}

fn build_modifier(py: Python<'_>, modifier: &ast::QuantumGateModifier) -> PyResult<Py<PyAny>> {
    let span = Span::from(modifier.span);
    let name = GateModifierName::from(&modifier.kind);
    let argument = match &modifier.kind {
        ast::GateModifierKind::Inv => None,
        ast::GateModifierKind::Pow(expr) => Some(build_expr(py, expr)?),
        ast::GateModifierKind::Ctrl(expr) | ast::GateModifierKind::NegCtrl(expr) => {
            opt_expr(py, expr.as_ref())?
        }
    };
    QuantumGateModifier::build(py, span, name, argument)
}

fn gate_operand_list(py: Python<'_>, operands: &[ast::GateOperand]) -> PyResult<Vec<Py<PyAny>>> {
    let mut out = Vec::with_capacity(operands.len());
    for operand in operands {
        collect_gate_operand(py, &mut out, operand)?;
    }
    Ok(out)
}

fn collect_gate_operand(
    py: Python<'_>,
    out: &mut Vec<Py<PyAny>>,
    operand: &ast::GateOperand,
) -> PyResult<()> {
    match &operand.kind {
        ast::GateOperandKind::IdentOrIndexedIdent(ident) => {
            out.push(build_ident_or_indexed(py, ident)?);
        }
        ast::GateOperandKind::HardwareQubit(hw) => out.push(build_hardware_qubit(py, hw)?),
        ast::GateOperandKind::Err => {}
    }
    Ok(())
}

fn build_index(py: Python<'_>, index: &ast::Index) -> PyResult<Py<PyAny>> {
    match index {
        ast::Index::DiscreteSet(set) => {
            let values = expr_list(py, &set.values)?;
            Ok(Py::new(py, DiscreteSet::init(Span::from(set.span), values))?.into_any())
        }
        ast::Index::IndexList(list) => {
            let mut values = Vec::with_capacity(list.values.len());
            for item in &list.values {
                match item {
                    ast::IndexListItem::RangeDefinition(range) => {
                        values.push(build_range(py, range)?);
                    }
                    ast::IndexListItem::Expr(expr) => values.push(build_expr(py, expr)?),
                    ast::IndexListItem::Err => {}
                }
            }
            Ok(Py::new(py, IndexList::init(Span::from(list.span), values))?.into_any())
        }
    }
}

fn build_range(py: Python<'_>, range: &ast::Range) -> PyResult<Py<PyAny>> {
    let start = opt_expr(py, range.start.as_ref())?;
    let step = opt_expr(py, range.step.as_ref())?;
    let end = opt_expr(py, range.end.as_ref())?;
    Ok(Py::new(
        py,
        RangeDefinition::init(Span::from(range.span), start, step, end),
    )?
    .into_any())
}

fn build_enumerable_set(py: Python<'_>, set: &ast::EnumerableSet) -> PyResult<Py<PyAny>> {
    match set {
        ast::EnumerableSet::DiscreteSet(set) => {
            let values = expr_list(py, &set.values)?;
            Ok(Py::new(py, DiscreteSet::init(Span::from(set.span), values))?.into_any())
        }
        ast::EnumerableSet::Range(range) => build_range(py, range),
        ast::EnumerableSet::Expr(expr) => build_expr(py, expr),
    }
}

