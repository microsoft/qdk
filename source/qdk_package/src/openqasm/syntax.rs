/// A read-only OpenQASM `SwitchStatement` node.
#[pyclass(extends = Statement, frozen, module = "qdk.openqasm.parser")]
pub(crate) struct SwitchStatement {
    /// The expression being switched on.
    #[pyo3(get)]
    target: Py<PyAny>,
    /// The `case` branches, in source order.
    #[pyo3(get)]
    cases: Vec<Py<PyAny>>,
    default: Option<Vec<Py<PyAny>>>,
}

#[pymethods]
impl SwitchStatement {
    /// The `default` branch's statements, or `None` when there is no `default`.
    #[getter]
    fn default(&self, py: Python<'_>) -> Option<Vec<Py<PyAny>>> {
        self.default
            .as_ref()
            .map(|body| body.iter().map(|stmt| stmt.clone_ref(py)).collect())
    }

    /// The node's child nodes: the annotations, the target, then the cases,
    /// then any default body.
    // `PyRef` is the receiver form PyO3 requires to reach the base class.
    #[allow(clippy::needless_pass_by_value)]
    fn children(slf: PyRef<'_, Self>) -> Vec<Py<PyAny>> {
        let py = slf.py();
        let annotations = &slf.as_super().annotations;
        let default_len = slf.default.as_ref().map_or(0, Vec::len);
        let mut children =
            Vec::with_capacity(annotations.len() + 1 + slf.cases.len() + default_len);
        children.extend(
            annotations
                .iter()
                .map(|annotation| annotation.clone_ref(py).into_any()),
        );
        children.push(slf.target.clone_ref(py));
        children.extend(slf.cases.iter().map(|case| case.clone_ref(py)));
        if let Some(default) = &slf.default {
            children.extend(default.iter().map(|stmt| stmt.clone_ref(py)));
        }
        children
    }

    fn __eq__(slf: &Bound<'_, Self>, other: &Bound<'_, PyAny>) -> PyResult<bool> {
        crate::openqasm::eq::structural_eq(
            slf.as_any(),
            other,
            &["annotations", "target", "cases", "default"],
        )
    }

    fn __hash__(slf: &Bound<'_, Self>) -> PyResult<isize> {
        crate::openqasm::eq::structural_hash(
            slf.as_any(),
            &["annotations", "target", "cases", "default"],
        )
    }
}

impl SwitchStatement {
    fn init(
        span: Span,
        annotations: Vec<Py<Annotation>>,
        target: Py<PyAny>,
        cases: Vec<Py<PyAny>>,
        default: Option<Vec<Py<PyAny>>>,
    ) -> PyClassInitializer<Self> {
        syntax_stmt_base(span, annotations).add_subclass(Self {
            target,
            cases,
            default,
        })
    }
}
