use super::super::apply_all_gates;
use crate::{CountingBackend, CountingBackendCounts, QirBackend};
use qsc::{LanguageFeatures, SourceMap, codegen::qir::get_qir, target::Profile};
use std::path::PathBuf;

struct QirFile(PathBuf);

impl QirFile {
    /// Creates a unique path for a temporary QIR file.
    fn new() -> Self {
        Self(std::env::temp_dir().join(format!(
            "qep-qsharp-{}-{}.ll",
            std::process::id(),
            rand::random::<u64>()
        )))
    }
}

impl Drop for QirFile {
    /// Removes the temporary QIR file if it was created.
    fn drop(&mut self) {
        if let Err(error) = std::fs::remove_file(&self.0)
            && error.kind() != std::io::ErrorKind::NotFound
        {
            eprintln!(
                "Failed to clean up QEP QIR file {}: {error}",
                self.0.display()
            );
        }
    }
}

#[test]
/// Verifies that the counting backend tracks every intrinsic and measurement.
fn counting_backend_reports_all_counts() -> Result<(), String> {
    let mut backend = CountingBackend::default();
    apply_all_gates(&mut backend)?;
    backend.mz(0, 0)?;
    backend.read_result(0)?;
    backend.mresetz(1, 1)?;
    backend.read_result(1)?;
    backend.write_result(2, true)?;
    assert!(backend.read_result(2)?);

    assert_eq!(
        *backend.counts(),
        CountingBackendCounts {
            ccx: 1,
            cx: 1,
            cy: 1,
            cz: 1,
            rx: 1,
            rxx: 1,
            ry: 1,
            ryy: 1,
            rz: 1,
            rzz: 1,
            h: 1,
            s: 1,
            sadj: 1,
            sx: 1,
            t: 1,
            tadj: 1,
            x: 1,
            y: 1,
            z: 1,
            swap: 1,
            mz: 1,
            reset: 1,
            mresetz: 1,
            read_result: 3,
            write_result: 1,
            measurements: 2,
        }
    );
    Ok(())
}

#[test]
/// Verifies that QIR compiled from Q# executes with the counting backend.
fn runs_qsharp_program() -> Result<(), String> {
    let source = r#"
        namespace Test {
            @EntryPoint()
            operation Main() : Result[] {
                use q = Qubit[2];
                H(q[0]);
                H(q[1]);
                [MResetZ(q[0]), MResetZ(q[1])]
            }
        }
    "#;
    let capabilities = Profile::Base.into();
    let (std_id, store) = qsc::compile::package_store_with_stdlib(capabilities);
    let qir = get_qir(
        SourceMap::new([("test.qs".into(), source.into())], None),
        LanguageFeatures::default(),
        capabilities,
        store,
        &[(std_id, None)],
    )
    .map_err(|errors| {
        errors
            .into_iter()
            .map(|error| error.to_string())
            .collect::<Vec<_>>()
            .join("\n")
    })?;
    let file = QirFile::new();
    std::fs::write(&file.0, qir).map_err(|error| error.to_string())?;

    let mut backend = CountingBackend::default();
    // SAFETY: The QIR was generated by the in-tree Q# compiler from trusted source.
    let output = unsafe { crate::run_qir(&file.0, &mut backend) }?;

    assert_eq!(output.return_value, Some(0));
    assert_eq!(output.records.len(), 3);
    assert_eq!(backend.counts().h, 2);
    assert_eq!(backend.counts().cx, 0);
    assert_eq!(backend.counts().ccx, 0);
    assert_eq!(backend.counts().read_result, 2);
    assert_eq!(backend.counts().read_result, 2);
    assert_eq!(backend.counts().write_result, 0);
    Ok(())
}
