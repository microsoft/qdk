use super::super::compile_qsharp_to_qir;
use crate::{OutputValue, SparseSimBackend, run_qir};
use num_bigint::BigUint;
use num_complex::Complex64;
use qsc::target::Profile;

/// Checks that the sparse simulator matches the expected nonzero amplitudes.
fn assert_wavefunction(backend: &mut SparseSimBackend, expected: &[(u32, Complex64)]) {
    let actual = backend.wavefunction();
    assert_eq!(actual.len(), expected.len());
    for (basis_state, amplitude) in expected {
        let (_, actual_amplitude) = actual
            .iter()
            .find(|(state, _)| state == &BigUint::from(*basis_state))
            .unwrap_or_else(|| panic!("missing basis state {basis_state}"));
        assert!(
            (*actual_amplitude - *amplitude).norm() < 1e-12,
            "wrong amplitude for basis state {basis_state}: {actual_amplitude:?}"
        );
    }
}

#[test]
/// Verifies deterministic gates and measurements through compiled Q#.
fn qsharp_gates_and_deterministic_measurements() -> Result<(), String> {
    let source = r#"
        namespace Test {
            @EntryPoint()
            operation Main() : Result[] {
                use qs = Qubit[2];
                X(qs[0]);
                CNOT(qs[0], qs[1]);
                [M(qs[0]), M(qs[1])]
            }
        }
    "#;
    let file = compile_qsharp_to_qir(source, Profile::Base);
    let mut backend = SparseSimBackend::default();
    // SAFETY: The QIR was generated by the in-tree Q# compiler from trusted source.
    let output = unsafe { run_qir(&file.0, &mut backend) }?;

    assert_eq!(
        output
            .records
            .iter()
            .map(|record| &record.value)
            .collect::<Vec<_>>(),
        vec![
            &OutputValue::Array(2),
            &OutputValue::Result(true),
            &OutputValue::Result(true),
        ]
    );
    assert_wavefunction(&mut backend, &[(3, Complex64::new(1.0, 0.0))]);
    Ok(())
}

#[test]
/// Verifies adaptive repeat-until-success execution and its final state.
fn qsharp_adaptive_repeat_until_success() -> Result<(), String> {
    let source = r#"
        namespace Test {
            @EntryPoint()
            operation Main() : Result {
                use q = Qubit();
                X(q);
                repeat {
                    X(q);
                } until M(q) == One;
                M(q)
            }
        }
    "#;
    let file = compile_qsharp_to_qir(source, Profile::Adaptive);
    let mut backend = SparseSimBackend::default();
    // SAFETY: The QIR was generated by the in-tree Q# compiler from trusted source.
    let output = unsafe { run_qir(&file.0, &mut backend) }?;

    assert_eq!(output.records.len(), 1);
    assert_eq!(output.records[0].value, OutputValue::Result(true));
    assert_wavefunction(&mut backend, &[(1, Complex64::new(1.0, 0.0))]);
    Ok(())
}

#[test]
/// Verifies a complex entangled state prepared by compiled Q#.
fn qsharp_prepares_complex_entangled_state() -> Result<(), String> {
    let source = r#"
        namespace Test {
            @EntryPoint()
            operation Main() : Unit {
                use qs = Qubit[2];
                H(qs[0]);
                T(qs[0]);
                CNOT(qs[0], qs[1]);
            }
        }
    "#;
    let file = compile_qsharp_to_qir(source, Profile::Base);
    let mut backend = SparseSimBackend::default();
    // SAFETY: The QIR was generated by the in-tree Q# compiler from trusted source.
    let _output = unsafe { run_qir(&file.0, &mut backend) }?;

    let inverse_sqrt_two = std::f64::consts::FRAC_1_SQRT_2;
    assert_wavefunction(
        &mut backend,
        &[
            (0, Complex64::new(inverse_sqrt_two, 0.0)),
            (
                3,
                Complex64::from_polar(inverse_sqrt_two, std::f64::consts::FRAC_PI_4),
            ),
        ],
    );
    Ok(())
}

