use crate::{
    OutputValue, QsBackendShim, QuantumBackend, QuantumBackends, ResultAdapter, TranspilingAdapter,
    run_qir,
};
use qsc::{CliffordSim, LanguageFeatures, SourceMap, codegen::qir::get_qir, target::Profile};
use qsc_eval::backend::SparseSim;
use std::{path::PathBuf, sync::Arc};

pub(crate) struct QirFile(pub(crate) PathBuf);

impl QirFile {
    /// Creates a unique path for a temporary QIR file.
    fn new() -> Self {
        Self(std::env::temp_dir().join(format!(
            "qep-qsharp-{}-{}.ll",
            std::process::id(),
            rand::random::<u64>()
        )))
    }

    /// Returns the temporary QIR path as UTF-8.
    pub(crate) fn path(&self) -> Result<&str, &str> {
        self.0
            .to_str()
            .ok_or("temporary QIR path is not valid UTF-8")
    }
}

impl Drop for QirFile {
    /// Removes the temporary QIR file if it was created.
    fn drop(&mut self) {
        if let Err(error) = std::fs::remove_file(&self.0)
            && error.kind() != std::io::ErrorKind::NotFound
        {
            eprintln!(
                "Failed to clean up QEP QIR file {}: {error}",
                self.0.display()
            );
        }
    }
}

/// Compiles Q# source to a temporary QIR file.
pub(crate) fn compile_qsharp_to_qir(source: &str, profile: Profile) -> QirFile {
    compile_qsharp_sources_to_qir(vec![("test.qs".into(), source.into())], profile)
}

/// Compiles Q# source together with the `library/arithmetic` sources to a temporary QIR file.
pub(crate) fn compile_qsharp_with_arithmetic_to_qir(source: &str, profile: Profile) -> QirFile {
    compile_qsharp_sources_to_qir(qsharp_sources_with_arithmetic(source), profile)
}

/// Loads the arithmetic library alongside the supplied Q# program.
pub(crate) fn qsharp_sources_with_arithmetic(source: &str) -> Vec<(Arc<str>, Arc<str>)> {
    let library_dir =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../library/arithmetic/src");
    let mut sources: Vec<(Arc<str>, Arc<str>)> = std::fs::read_dir(&library_dir)
        .expect("failed to read arithmetic library directory")
        .map(|entry| {
            let path = entry.expect("failed to read directory entry").path();
            let name = path
                .file_name()
                .and_then(|name| name.to_str())
                .expect("arithmetic library file name should be valid UTF-8");
            let contents =
                std::fs::read_to_string(&path).expect("failed to read arithmetic library file");
            (name.into(), contents.into())
        })
        .collect();
    sources.push(("test.qs".into(), source.into()));
    sources
}

/// Compiles the given named Q# sources to a temporary QIR file.
fn compile_qsharp_sources_to_qir(sources: Vec<(Arc<str>, Arc<str>)>, profile: Profile) -> QirFile {
    let capabilities = profile.into();
    let (std_id, store) = qsc::compile::package_store_with_stdlib(capabilities);
    let qir = get_qir(
        SourceMap::new(sources, None),
        LanguageFeatures::default(),
        capabilities,
        store,
        &[(std_id, None)],
    )
    .unwrap_or_else(|errors| {
        panic!(
            "{}",
            errors
                .into_iter()
                .map(|error| error.to_string())
                .collect::<Vec<_>>()
                .join("\n")
        )
    });
    let file = QirFile::new();
    std::fs::write(&file.0, qir).expect("failed to write compiled QIR");
    file
}

#[test]
/// Verifies one compiled adder with multiple simulators and result adapters.
fn qsharp_adder_with_different_backends() -> Result<(), String> {
    /// Checks the compiled adder's output using a concrete backend type.
    fn assert_adder_result(
        file: &QirFile,
        backend: &mut impl QuantumBackend,
    ) -> Result<(), String> {
        // SAFETY: The QIR was generated by the in-tree Q# compiler from trusted source.
        let output = unsafe { run_qir(&file.0, backend) }?;
        assert_eq!(output.records.len(), 1);
        assert_eq!(output.records[0].value, OutputValue::Int(22));
        Ok(())
    }

    let source = r#"
        namespace Test {
            @EntryPoint()
            operation Main() : Int {
                use x = Qubit[5];
                use y = Qubit[5];
                use carry = Qubit();
                ApplyXorInPlace(7, x);
                ApplyXorInPlace(15, y);
                Std.Arithmetic.RippleCarryTTKIncByLE(x, y + [carry]);
                Std.Measurement.MeasureInteger(y)
            }
        }
    "#;
    let file = compile_qsharp_to_qir(source, Profile::Adaptive);
    let qir = std::fs::read_to_string(&file.0).map_err(|error| error.to_string())?;
    assert!(qir.contains("\"required_num_qubits\"=\"11\""));

    assert_adder_result(&file, &mut QuantumBackends::sparse_sim())?;
    assert_adder_result(&file, &mut QsBackendShim::new(SparseSim::new()))?;
    assert_adder_result(
        &file,
        &mut TranspilingAdapter::with_defaults(QsBackendShim::new(CliffordSim::new(11))),
    )?;
    assert_adder_result(
        &file,
        &mut ResultAdapter::new(QuantumBackends::sparse_sim()),
    )?;
    assert_adder_result(
        &file,
        &mut ResultAdapter::new(QsBackendShim::new(SparseSim::new())),
    )?;
    assert_adder_result(
        &file,
        &mut ResultAdapter::new(TranspilingAdapter::with_defaults(QsBackendShim::new(
            CliffordSim::new(11),
        ))),
    )?;
    Ok(())
}
